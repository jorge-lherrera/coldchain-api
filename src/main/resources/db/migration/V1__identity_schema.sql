CREATE TABLE ORGANIZATION (
    ID            RAW(16)                        NOT NULL,
    TAX_ID        VARCHAR2(64 CHAR)              NOT NULL,
    LEGAL_NAME    VARCHAR2(200 CHAR)             NOT NULL,
    TRADE_NAME    VARCHAR2(200 CHAR),
    KIND          VARCHAR2(20 CHAR)              NOT NULL,
    COUNTRY       CHAR(2 CHAR)                   NOT NULL,
    STATUS        VARCHAR2(20 CHAR)              NOT NULL,
    LOCK_VERSION  NUMBER(10)                     DEFAULT 0 NOT NULL,
    CREATED_AT    TIMESTAMP(6) WITH TIME ZONE    NOT NULL,
    CREATED_BY    RAW(16)                        NOT NULL,
    UPDATED_AT    TIMESTAMP(6) WITH TIME ZONE,
    UPDATED_BY    RAW(16),
    CONSTRAINT PK_ORGANIZATION PRIMARY KEY (ID),
    CONSTRAINT UQ_ORGANIZATION_TAX_ID UNIQUE (TAX_ID),
    CONSTRAINT CK_ORGANIZATION_KIND CHECK (KIND IN ('SHIPPER', 'CARRIER', 'WAREHOUSE', 'LAB')),
    CONSTRAINT CK_ORGANIZATION_STATUS CHECK (STATUS IN ('ACTIVE', 'SUSPENDED')),
    CONSTRAINT CK_ORGANIZATION_TAX_ID_BLANK CHECK (TRIM(TAX_ID) IS NOT NULL),
    CONSTRAINT CK_ORGANIZATION_LEGAL_NAME_BLANK CHECK (TRIM(LEGAL_NAME) IS NOT NULL),
    CONSTRAINT CK_ORGANIZATION_COUNTRY_BLANK CHECK (TRIM(COUNTRY) IS NOT NULL)
);

CREATE TABLE APP_USER (
    ID                     RAW(16)                        NOT NULL,
    ORGANIZATION_ID        RAW(16)                        NOT NULL,
    EMAIL                  VARCHAR2(320 CHAR)             NOT NULL,
    PASSWORD_HASH          VARCHAR2(200 CHAR),
    FULL_NAME              VARCHAR2(200 CHAR)             NOT NULL,
    STATUS                 VARCHAR2(20 CHAR)              NOT NULL,
    ACTIVATION_TOKEN_HASH  VARCHAR2(64 CHAR),
    ACTIVATION_EXPIRES_AT  TIMESTAMP(6) WITH TIME ZONE,
    LAST_LOGIN_AT          TIMESTAMP(6) WITH TIME ZONE,
    LOCK_VERSION           NUMBER(10)                     DEFAULT 0 NOT NULL,
    CREATED_AT             TIMESTAMP(6) WITH TIME ZONE    NOT NULL,
    CREATED_BY             RAW(16)                        NOT NULL,
    UPDATED_AT             TIMESTAMP(6) WITH TIME ZONE,
    UPDATED_BY             RAW(16),
    CONSTRAINT PK_APP_USER PRIMARY KEY (ID),
    CONSTRAINT FK_APP_USER_ORGANIZATION FOREIGN KEY (ORGANIZATION_ID) REFERENCES ORGANIZATION (ID),
    CONSTRAINT CK_APP_USER_STATUS CHECK (STATUS IN ('INVITED', 'ACTIVE', 'SUSPENDED')),
    CONSTRAINT CK_APP_USER_EMAIL_BLANK CHECK (TRIM(EMAIL) IS NOT NULL),
    CONSTRAINT CK_APP_USER_FULL_NAME_BLANK CHECK (TRIM(FULL_NAME) IS NOT NULL),
    CONSTRAINT CK_APP_USER_ACTIVE_HAS_PASSWORD CHECK (STATUS <> 'ACTIVE' OR PASSWORD_HASH IS NOT NULL)
);

CREATE UNIQUE INDEX UX_APP_USER_EMAIL_LOWER ON APP_USER (LOWER(EMAIL));

CREATE INDEX IX_APP_USER_ORGANIZATION_ID ON APP_USER (ORGANIZATION_ID);

CREATE TABLE ROLE (
    ID          RAW(16)                        NOT NULL,
    CODE        VARCHAR2(40 CHAR)              NOT NULL,
    NAME        VARCHAR2(100 CHAR)             NOT NULL,
    BUILT_IN    NUMBER(1)                      NOT NULL,
    CREATED_AT  TIMESTAMP(6) WITH TIME ZONE    NOT NULL,
    CREATED_BY  RAW(16)                        NOT NULL,
    UPDATED_AT  TIMESTAMP(6) WITH TIME ZONE,
    UPDATED_BY  RAW(16),
    CONSTRAINT PK_ROLE PRIMARY KEY (ID),
    CONSTRAINT UQ_ROLE_CODE UNIQUE (CODE),
    CONSTRAINT CK_ROLE_BUILT_IN CHECK (BUILT_IN IN (0, 1)),
    CONSTRAINT CK_ROLE_CODE_BLANK CHECK (TRIM(CODE) IS NOT NULL),
    CONSTRAINT CK_ROLE_NAME_BLANK CHECK (TRIM(NAME) IS NOT NULL)
);

CREATE TABLE ROLE_SCOPE (
    ROLE_ID     RAW(16)                        NOT NULL,
    SCOPE_CODE  VARCHAR2(60 CHAR)              NOT NULL,
    CREATED_AT  TIMESTAMP(6) WITH TIME ZONE    NOT NULL,
    CREATED_BY  RAW(16)                        NOT NULL,
    UPDATED_AT  TIMESTAMP(6) WITH TIME ZONE,
    UPDATED_BY  RAW(16),
    CONSTRAINT PK_ROLE_SCOPE PRIMARY KEY (ROLE_ID, SCOPE_CODE),
    CONSTRAINT FK_ROLE_SCOPE_ROLE FOREIGN KEY (ROLE_ID) REFERENCES ROLE (ID) ON DELETE CASCADE,
    CONSTRAINT CK_ROLE_SCOPE_CODE_BLANK CHECK (TRIM(SCOPE_CODE) IS NOT NULL)
);

CREATE TABLE USER_ROLE (
    APP_USER_ID  RAW(16)                        NOT NULL,
    ROLE_ID      RAW(16)                        NOT NULL,
    GRANTED_BY   RAW(16),
    GRANTED_AT   TIMESTAMP(6) WITH TIME ZONE    NOT NULL,
    CREATED_AT   TIMESTAMP(6) WITH TIME ZONE    NOT NULL,
    CREATED_BY   RAW(16)                        NOT NULL,
    UPDATED_AT   TIMESTAMP(6) WITH TIME ZONE,
    UPDATED_BY   RAW(16),
    CONSTRAINT PK_USER_ROLE PRIMARY KEY (APP_USER_ID, ROLE_ID),
    CONSTRAINT FK_USER_ROLE_APP_USER FOREIGN KEY (APP_USER_ID) REFERENCES APP_USER (ID) ON DELETE CASCADE,
    CONSTRAINT FK_USER_ROLE_ROLE FOREIGN KEY (ROLE_ID) REFERENCES ROLE (ID),
    CONSTRAINT FK_USER_ROLE_GRANTED_BY FOREIGN KEY (GRANTED_BY) REFERENCES APP_USER (ID) ON DELETE SET NULL
);

CREATE INDEX IX_USER_ROLE_ROLE_ID ON USER_ROLE (ROLE_ID);

CREATE INDEX IX_USER_ROLE_GRANTED_BY ON USER_ROLE (GRANTED_BY);


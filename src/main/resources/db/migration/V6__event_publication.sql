CREATE TABLE EVENT_PUBLICATION (
    ID                      RAW(16)                        NOT NULL,
    LISTENER_ID             VARCHAR2(512 CHAR)             NOT NULL,
    EVENT_TYPE              VARCHAR2(512 CHAR)             NOT NULL,
    SERIALIZED_EVENT        VARCHAR2(4000 BYTE)            NOT NULL,
    PUBLICATION_DATE        TIMESTAMP(6) WITH TIME ZONE    NOT NULL,
    COMPLETION_DATE         TIMESTAMP(6) WITH TIME ZONE,
    STATUS                  VARCHAR2(20 CHAR),
    COMPLETION_ATTEMPTS     NUMBER(10)                     DEFAULT 0 NOT NULL,
    LAST_RESUBMISSION_DATE  TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT PK_EVENT_PUBLICATION PRIMARY KEY (ID),
    CONSTRAINT CK_EVENT_PUBLICATION_STATUS CHECK (STATUS IN
        ('PUBLISHED', 'PROCESSING', 'COMPLETED', 'FAILED', 'RESUBMITTED'))
);

CREATE INDEX IX_EVENT_PUBLICATION_LISTENER_EVENT ON EVENT_PUBLICATION (LISTENER_ID, SERIALIZED_EVENT);

CREATE INDEX IX_EVENT_PUBLICATION_COMPLETION ON EVENT_PUBLICATION (COMPLETION_DATE);

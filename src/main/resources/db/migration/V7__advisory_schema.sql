CREATE TABLE EXCURSION_ALERT (
    ID                  RAW(16)                        NOT NULL,
    ORGANIZATION_ID     RAW(16)                        NOT NULL,
    SHIPMENT_ID         RAW(16)                        NOT NULL,
    EXCURSION_ID        RAW(16)                        NOT NULL,
    PROBABLE_CAUSE      VARCHAR2(32 CHAR)              NOT NULL,
    SEVERITY            VARCHAR2(8 CHAR)               NOT NULL,
    CONFIDENCE          NUMBER(3,2),
    SUMMARY_EN          VARCHAR2(1000 CHAR)            NOT NULL,
    SUMMARY_ES          VARCHAR2(1000 CHAR)            NOT NULL,
    SUMMARY_PT          VARCHAR2(1000 CHAR)            NOT NULL,
    RECOMMENDED_ACTION  VARCHAR2(500 CHAR)             NOT NULL,
    SOURCE              VARCHAR2(8 CHAR)               NOT NULL,
    MODEL               VARCHAR2(100 CHAR),
    CONTEXT_AVAILABLE   NUMBER(1)                      NOT NULL,
    TRIAGED_AT          TIMESTAMP(6) WITH TIME ZONE    NOT NULL,
    LOCK_VERSION        NUMBER(10)                     DEFAULT 0 NOT NULL,
    CREATED_AT          TIMESTAMP(6) WITH TIME ZONE    NOT NULL,
    CREATED_BY          RAW(16)                        NOT NULL,
    UPDATED_AT          TIMESTAMP(6) WITH TIME ZONE,
    UPDATED_BY          RAW(16),
    CONSTRAINT PK_EXCURSION_ALERT PRIMARY KEY (ID),
    CONSTRAINT FK_EXCURSION_ALERT_ORGANIZATION FOREIGN KEY (ORGANIZATION_ID) REFERENCES ORGANIZATION (ID),
    CONSTRAINT UQ_EXCURSION_ALERT_EXCURSION_ID UNIQUE (EXCURSION_ID),
    CONSTRAINT CK_EXCURSION_ALERT_PROBABLE_CAUSE CHECK (PROBABLE_CAUSE IN
        ('HANDLING_DURING_HANDOFF', 'REFRIGERATION_FAILURE', 'DOOR_OPENING', 'SENSOR_FAULT', 'UNKNOWN')),
    CONSTRAINT CK_EXCURSION_ALERT_SEVERITY CHECK (SEVERITY IN ('LOW', 'MEDIUM', 'HIGH')),
    CONSTRAINT CK_EXCURSION_ALERT_SOURCE CHECK (SOURCE IN ('LLM', 'RULES')),
    CONSTRAINT CK_EXCURSION_ALERT_CONFIDENCE CHECK (CONFIDENCE BETWEEN 0 AND 1),
    CONSTRAINT CK_EXCURSION_ALERT_CONTEXT_AVAILABLE CHECK (CONTEXT_AVAILABLE IN (0, 1)),
    CONSTRAINT CK_EXCURSION_ALERT_MODEL CHECK ((SOURCE = 'LLM' AND MODEL IS NOT NULL)
        OR (SOURCE = 'RULES' AND MODEL IS NULL)),
    CONSTRAINT CK_EXCURSION_ALERT_SUMMARY_EN_BLANK CHECK (TRIM(SUMMARY_EN) IS NOT NULL),
    CONSTRAINT CK_EXCURSION_ALERT_SUMMARY_ES_BLANK CHECK (TRIM(SUMMARY_ES) IS NOT NULL),
    CONSTRAINT CK_EXCURSION_ALERT_SUMMARY_PT_BLANK CHECK (TRIM(SUMMARY_PT) IS NOT NULL),
    CONSTRAINT CK_EXCURSION_ALERT_RECOMMENDED_ACTION_BLANK CHECK (TRIM(RECOMMENDED_ACTION) IS NOT NULL)
);

CREATE INDEX IX_EXCURSION_ALERT_ORGANIZATION_ID ON EXCURSION_ALERT (ORGANIZATION_ID);

CREATE INDEX IX_EXCURSION_ALERT_SHIPMENT_ID_TRIAGED_AT ON EXCURSION_ALERT (SHIPMENT_ID, TRIAGED_AT);
